"use client";
import { useEffect, useRef, useState, useSyncExternalStore } from "react";
import confetti from "canvas-confetti";
import { getCheers, postCheer } from "@/lib/api/cheers";

const CHEERED_KEY = "interview-vault:cheered";
const CHEERED_EVENT = "interview-vault:cheered-change";

function readCheered(): boolean {
  if (typeof window === "undefined") return false;
  return window.localStorage.getItem(CHEERED_KEY) === "1";
}

function subscribeCheered(onChange: () => void) {
  const onStorage = (event: StorageEvent) => {
    if (event.key === CHEERED_KEY || event.key === null) onChange();
  };
  window.addEventListener("storage", onStorage);
  window.addEventListener(CHEERED_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onStorage);
    window.removeEventListener(CHEERED_EVENT, onChange);
  };
}

function readServerCheered(): boolean {
  return false;
}

/**
 * 页尾祝福条：一句祝福 + 「接受祝福」+「已有 N 人接受了这份祝福」整体居中成一行（850px 内）。
 * 每人一次由 localStorage 承诺（登录用户后端唯一约束兜底）。
 */
export function CheerBar() {
  const [count, setCount] = useState<number | null>(null);
  const cheered = useSyncExternalStore(subscribeCheered, readCheered, readServerCheered);
  const [busy, setBusy] = useState(false);
  const button = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    // cheered 态由 useSyncExternalStore 订阅（跨标签页同步）；这里只拉计数
    let alive = true;
    getCheers()
      .then((response) => {
        if (alive) setCount(response.count);
      })
      .catch(() => {
        if (alive) setCount(null);
      });
    return () => {
      alive = false;
    };
  }, []);

  /** 轻礼花：按钮左右两个发射点、小角度上抛、克制的蓝金配色，约 1s 散尽。 */
  function fireConfetti() {
    const rect = button.current?.getBoundingClientRect();
    if (!rect) return;
    const originY = (rect.top + rect.height / 2) / window.innerHeight;
    const options = {
      spread: 55,
      startVelocity: 26,
      gravity: 0.9,
      scalar: 0.75,
      ticks: 90,
      colors: ["#7da7ff", "#9dbcf2", "#ffd479", "#8fd6b5", "#c9a7f5"],
      disableForReducedMotion: true,
    };
    confetti({
      ...options,
      particleCount: 22,
      origin: { x: (rect.left + rect.width * 0.2) / window.innerWidth, y: originY },
      angle: 60,
    });
    confetti({
      ...options,
      particleCount: 22,
      origin: { x: (rect.left + rect.width * 0.8) / window.innerWidth, y: originY },
      angle: 120,
    });
  }

  async function cheer() {
    if (cheered || busy) return;
    setBusy(true);
    try {
      const response = await postCheer();
      setCount(response.count);
      window.localStorage.setItem(CHEERED_KEY, "1");
      window.dispatchEvent(new Event(CHEERED_EVENT));
      fireConfetti();
    } catch {
      // 点击失败保持原状，用户可重试
    } finally {
      setBusy(false);
    }
  }

  return (
    <footer className="cheer-bar">
      <div className="cheer-line">
        <svg
          className="cheer-mail"
          viewBox="0 0 1024 1024"
          fill="currentColor"
          aria-hidden="true"
        >
          <path d="M838.954667 234.666667H170.666667c-3.626667 0-7.168 0.448-10.56 1.322666l323.690666 323.669334a21.333333 21.333333 0 0 0 30.165334 0L838.954667 234.666667z m46.144 14.186666l-260.693334 260.693334 262.933334 262.912c5.44-7.168 8.661333-16.106667 8.661333-25.792V277.333333c0-10.944-4.117333-20.906667-10.88-28.48zM843.861333 789.333333l-249.6-249.621333-50.133333 50.133333a64 64 0 0 1-90.517333 0l-50.112-50.133333L156.373333 786.88c4.48 1.578667 9.28 2.453333 14.314667 2.453333h673.194667zM128.661333 754.218667L373.333333 509.525333 129.578667 265.813333A42.709333 42.709333 0 0 0 128 277.333333v469.333334c0 2.56 0.213333 5.098667 0.661333 7.552zM170.666667 192h682.666666a85.333333 85.333333 0 0 1 85.333334 85.333333v469.333334a85.333333 85.333333 0 0 1-85.333334 85.333333H170.666667a85.333333 85.333333 0 0 1-85.333334-85.333333V277.333333a85.333333 85.333333 0 0 1 85.333334-85.333333z" />
        </svg>
        <span className="cheer-message">
          愿下一封来信，是你期待已久的 Offer！
        </span>
        <button
          ref={button}
          type="button"
          className={`cheer-button${cheered ? " cheer-button-done" : ""}`}
          disabled={cheered || busy}
          onClick={() => void cheer()}
        >
          {cheered ? (
            <>
              已接受
              <svg
                className="cheer-cherry"
                viewBox="0 0 1024 1024"
                aria-hidden="true"
              >
                <path
                  d="M604.896264 36.076959c29.450579-21.487074 75.623669-31.870942 110.693554-13.532033 27.072529 16.688661 57.293223 41.38314 61.270744 74.802776 7.955041 45.360661-3.977521 92.515438-27.072529 129.819505 18.338909 62.032397 50.979967 117.929256 46.181554 188.805289-7.134149 92.303868-61.270744 188.644496-152.796033 219.694545-35.950017 9.503736-70.199008 23.814347-107.545389 28.672-2.369587 3.249719-6.406347 6.347107-7.176463 9.60529 0 105.793587 0 220.523901-8.005818 327.197619-7.904264 15.910083-27.013289 23.915901-42.144793 15.131505-7.193388-3.249719-11.932562-10.324628-15.190744-17.560331-5.526215-104.244893-4.705322-216.647934-7.904264-324.768793-31.100826-20.818512-74.845091-19.168264-108.264728-38.27729-93.962579-35.89924-143.343074-133.069223-145.721124-229.308297 4.756099-64.57124 24.643702-122.685355 50.159075-179.2-14.259835-43.651174-45.402975-89.875041-23.095008-139.314777 19.066711-50.269091 70.876033-78.111736 121.805223-78.881851 23.086545 1.599471 41.374678 11.153983 61.313058 19.159801C451.998678 17.018711 495.032066-10.155372 539.554909 11.340165c23.145785 4.857653 37.447934 36.728595 65.341355 24.745256"
                  fill="#231916"
                />
                <path
                  d="M545.174215 89.451901c11.111669 22.31643 0 68.497983 38.277289 62.971768 24.584463-25.625388 21.436298-76.503802 66.839273-79.711206 21.495537-4.747636 44.582083-3.249719 59.66281 12.812694 18.389686 19.066711 19.93838 50.057521 12.761917 74.752-8.682843 30.271471-45.301421 54.187372-34.198215 87.657785 38.996628 59.66281 69.217322 129.658711 47.781025 206.170975-9.562975 70.918347-81.251438 124.284826-144.891769 141.743604-97.212298 23.095008-210.283901 14.302149-285.078214-51.758546-44.582083-47.840264-57.335537-113.799405-47.831802-179.098446 4.747636-56.616198 54.238149-96.442182 51.809322-152.956827-21.537851-33.470413-51.809322-74.743537-28.722777-114.730314 18.338909-20.666182 39.87676-32.598744 68.548761-27.013289 19.887603 5.627769 42.144793 19.159802 47.679471 39.72443 4.84919 19.210579 5.627769 40.756893 25.557686 51.758545 50.937653-3.82519 4.705322-64.469686 38.175735-87.454677 23.915901-15.139967 69.327339-15.96086 83.629488 15.131504"
                  fill="#EE90B2"
                />
                <path
                  d="M369.232397 754.341025c48.55114 62.142413 39.817521 162.359008 7.955041 229.198281-47.789488 30.271471-113.080066 11.213223-156.824331-13.481256-76.453025-55.685289-131.461289-141.752066-112.301487-240.462281 6.35557-22.984992 17.568793-50.937653 43.803504-58.892695 83.629488-21.487074 170.356364 6.35557 217.35881 83.637951M910.615273 735.164298c18.338909 91.482975-20.666182 178.379107-99.488794 231.737123-50.979967 36.627041-122.626116 58.943471-185.538644 31.820166-41.425455-23.814347-39.825983-78.822612-38.167273-124.132496-0.829355-71.696926 61.253818-133.797025 120.188826-164.060033 56.514645-21.597091 128.981686-25.523835 185.445554-1.607934 9.656066 7.193388 13.633587 16.739438 17.560331 26.251636"
                  fill="#231916"
                />
                <path
                  d="M334.958017 798.127603c18.279669 40.655339 23.035769 93.141686 4.028297 133.797025-15.139967 25.413818-48.61038 8.67438-70.918347 7.955041-58.892694-19.168264-97.889322-78.111736-109.102546-135.404958-3.918281-26.234711-1.548694-54.957488 9.613753-76.444562 63.741884-19.887603 132.950744 10.383868 166.378843 70.097454M853.305124 758.369322c19.117488 44.480529 0 92.312331-25.464595 128.05924-45.402975 48.61038-105.108099 81.310678-172.006612 61.423074-25.464595-30.381488-7.904264-78.873388 0-113.181619 23.095008-46.951669 70.86757-89.113388 124.284827-89.934281 27.013289-0.770116 52.528661 0.829355 73.18638 13.642049"
                  fill="#15AB4A"
                />
              </svg>
            </>
          ) : busy ? (
            "接受中…"
          ) : (
            "接受祝福"
          )}
        </button>
        {count !== null && (
          <span className="cheer-count">
            已有 <strong>{count.toLocaleString()}</strong> 人接受了这份祝福
          </span>
        )}
      </div>

    </footer>
  );
}
